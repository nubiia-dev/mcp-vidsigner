#!/usr/bin/env node
/**
 * Generates src/client/generated/vidsigner-api.ts (TypeScript types of the signature API DTOs)
 * from the VIDsigner OpenAPI document with openapi-typescript.
 *
 * Usage:
 *   VIDSIGNER_SPEC_DIR=/path/to/vendor-docs npm run gen:types
 *   npm run gen:types -- --spec-dir /path/to/vendor-docs
 *
 * The OpenAPI document belongs to Validated ID (available to its customers) and is not
 * redistributed with this repository; only the generated types are versioned. Descriptive text of
 * the vendor document (summaries, descriptions, examples) is stripped before generating, so the
 * output carries structure only.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { requireOpenApi, runScript } from './lib/spec-dir.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = 'src/client/generated/vidsigner-api.ts';
const BANNER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;
const PROSE_KEYS = new Set(['summary', 'description', 'example', 'examples', 'externalDocs']);

/**
 * Removes the descriptive text of an OpenAPI node tree. Keys inside a `properties` map are DTO
 * property names, never documentation, so they are kept.
 * @param {unknown} node
 * @param {boolean} insideProperties
 * @returns {unknown}
 */
function stripProse(node, insideProperties = false) {
  if (Array.isArray(node)) return node.map((n) => stripProse(n));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (!insideProperties && PROSE_KEYS.has(key)) continue;
    out[key] = stripProse(value, !insideProperties && key === 'properties');
  }
  return out;
}

await runScript(async () => {
  const spec = JSON.parse(readFileSync(requireOpenApi(), 'utf8'));
  const ast = await openapiTS(stripProse(spec));
  writeFileSync(resolve(ROOT, OUT), BANNER + astToString(ast));
  // openapi-typescript does not format its output with the repository's prettier settings.
  const prettier = resolve(ROOT, 'node_modules/prettier/bin/prettier.cjs');
  const fmt = spawnSync(process.execPath, [prettier, '--write', OUT], {
    cwd: ROOT,
    stdio: 'inherit',
  });
  if (fmt.status !== 0) process.exit(fmt.status ?? 1);
  console.log(`generated ${OUT}`);
});
