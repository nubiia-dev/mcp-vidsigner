/**
 * API surface: the structural facts about the VIDsigner signature API that the generators and the
 * tests need (operations, parameters, DTO property names and types), without any documentation text.
 *
 * It is extracted once from the vendor OpenAPI document (`npm run gen:schemas`, which needs
 * `VIDSIGNER_SPEC_DIR`) and versioned as `data/openapi-surface.json`, so that the zod schemas can be
 * regenerated, and the test suite can verify them, without redistributing the vendor document.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import prettier from 'prettier';

/** Repository root. */
export const ROOT = resolve(import.meta.dirname, '..', '..');

/** Versioned location of the extracted surface, relative to the repository root. */
export const SURFACE_PATH = 'data/openapi-surface.json';

/** One DTO property, with `$ref` targets already reduced to short schema names. */
export interface SurfaceProperty {
  type?: string;
  format?: string;
  /** Short name of the referenced schema (`Signer.SignerV2DTO`...). */
  ref?: string;
  items?: SurfaceProperty;
  /** True when the property is an object with `additionalProperties` (a string dictionary). */
  map?: boolean;
}

/** One API operation. */
export interface SurfaceOperation {
  method: string;
  /** Path without the `/api/v{version}` prefix, parameter names kept (`/documents/{documentGuid}`). */
  path: string;
  /** Parameters other than `version`. */
  params: Array<{ in: string; name: string }>;
  /** Short name of the request body schema, when the operation has a body. */
  bodyRef?: string;
}

/** The whole surface. */
export interface Surface {
  $comment: string;
  operations: SurfaceOperation[];
  schemas: Record<string, Record<string, SurfaceProperty>>;
}

interface OaProperty {
  type?: string;
  format?: string;
  $ref?: string;
  items?: OaProperty;
  additionalProperties?: OaProperty | boolean;
}
interface OaOperation {
  parameters?: Array<{ in: string; name: string }>;
  requestBody?: { content: Record<string, { schema: OaProperty }> };
}
interface OpenApi {
  paths: Record<string, Record<string, OaOperation>>;
  components: { schemas: Record<string, { properties?: Record<string, OaProperty> }> };
}

const PREFIXES = [
  'VIDCloudRestPubDTOs.DTOs.',
  'VIDCloudRestPubDTOs.DTOEntities.',
  'VIDCloudRestPrivDTOs.DTOs.',
];

/** Short name of an OpenAPI schema (`Signer.SignerV2DTO`, `VisibleDTO`...). */
export function shortName(full: string): string {
  for (const p of PREFIXES) if (full.startsWith(p)) return full.slice(p.length);
  return full;
}

const refName = (ref: string): string => shortName(ref.split('/').pop() as string);

function toProperty(prop: OaProperty): SurfaceProperty {
  const out: SurfaceProperty = {};
  if (prop.$ref) out.ref = refName(prop.$ref);
  if (prop.type) out.type = prop.type;
  if (prop.format) out.format = prop.format;
  if (prop.items) out.items = toProperty(prop.items);
  if (typeof prop.additionalProperties === 'object') out.map = true;
  return out;
}

/** Extracts the surface from the vendor OpenAPI document (JSON text). */
export function extractSurface(openApiText: string): Surface {
  const spec = JSON.parse(openApiText) as OpenApi;
  const schemas: Surface['schemas'] = {};
  for (const [full, schema] of Object.entries(spec.components.schemas)) {
    const name = shortName(full);
    if (schemas[name]) throw new Error(`Two OpenAPI schemas share the short name ${name}`);
    schemas[name] = Object.fromEntries(
      Object.entries(schema.properties ?? {}).map(([k, v]) => [k, toProperty(v)]),
    );
  }
  const operations: SurfaceOperation[] = [];
  for (const [rawPath, methods] of Object.entries(spec.paths)) {
    const path = rawPath.replace('/api/v{version}', '');
    for (const [method, op] of Object.entries(methods)) {
      const body = Object.values(op.requestBody?.content ?? {})[0]?.schema.$ref;
      operations.push({
        method: method.toUpperCase(),
        path,
        params: (op.parameters ?? [])
          .filter((p) => p.name !== 'version')
          .map((p) => ({ in: p.in, name: p.name })),
        ...(body ? { bodyRef: refName(body) } : {}),
      });
    }
  }
  operations.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));
  return {
    $comment:
      'GENERATED by scripts/gen-body-schemas.ts from the VIDsigner OpenAPI document. Structural facts only (operations, parameter names, DTO property names and types). Do not edit by hand: npm run gen:schemas.',
    operations,
    schemas,
  };
}

/** Reads the versioned surface. */
export function loadSurface(): Surface {
  return JSON.parse(readFileSync(resolve(ROOT, SURFACE_PATH), 'utf8')) as Surface;
}

/** Serialises the surface exactly as it is versioned (formatted with the repository's prettier config). */
export async function renderSurface(surface: Surface): Promise<string> {
  const target = resolve(ROOT, SURFACE_PATH);
  return prettier.format(JSON.stringify(surface), {
    ...(await prettier.resolveConfig(target)),
    filepath: target,
  });
}
