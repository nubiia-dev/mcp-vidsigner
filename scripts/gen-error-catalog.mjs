#!/usr/bin/env node
/**
 * Generates src/client/errors/catalog.generated.ts from the text of the VIDsigner REST manual
 * (Annex III: Error reference guide).
 *
 * Usage:
 *   VIDSIGNER_SPEC_DIR=/path/to/vendor-docs npm run gen:errors
 *   npm run gen:errors -- --spec-dir /path/to/vendor-docs
 *
 * The manual belongs to Validated ID (available to its customers) and is not redistributed with
 * this repository; only the generated catalog is versioned. The text comes from `pdftotext` run on
 * the manual PDF. The script finds section "16.2 Errors by endpoint" and collects every row
 * `HTTP  Code  Message`. Messages that span several lines in the PDF are joined. The catalog is
 * only a diagnostic aid and is never used to decide business logic.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireManual, runScript } from './lib/spec-dir.mjs';

await runScript(() => {
  const input = requireManual();
  const lines = readFileSync(input, 'utf8').split('\n');
  const start = lines.findIndex((l) => /^16\.2\.1\s+Common Authentication Errors/.test(l.trim()));
  if (start < 0) {
    console.error('Section 16.2.1 of Annex III was not found in the manual text.');
    process.exit(1);
  }

  /** @type {Map<number, {http:number, message:string, endpoints:Set<string>}>} */
  const catalog = new Map();
  let endpoint = 'common';
  /** Open row: its continuation lines (message split by the PDF) are appended. */
  let open = null;

  /** Joins fragments of a message split over several lines (the PDF hyphenates). */
  function joinFragment(base, frag) {
    return base.endsWith('-') ? base.slice(0, -1) + frag : `${base} ${frag}`;
  }

  for (const raw of lines.slice(start)) {
    const line = raw.trimEnd();
    const head = line.match(/^16\.2\.\d+\s+((?:GET|POST|PUT|DELETE)\s+\S+)/);
    if (head) {
      endpoint = head[1].replace('/api/v3.0', '');
      open = null;
      continue;
    }
    const row = line.match(/^(\s*)(\d{3})(\s+)(\d{3,6})(\s{2,})(\S.*?)(?:\s{2,}\S.*)?$/);
    if (row) {
      const http = Number(row[2]);
      const code = Number(row[4]);
      const message = row[6].trim().replace(/\s+/g, ' ');
      const msgCol = row[1].length + row[2].length + row[3].length + row[4].length + row[5].length;
      open = null;
      if (http < 400 || http > 599) continue;
      let entry = catalog.get(code);
      if (entry) entry.endpoints.add(endpoint);
      else {
        entry = { http, message, endpoints: new Set([endpoint]) };
        catalog.set(code, entry);
        open = { entry, msgCol };
      }
      continue;
    }
    if (open) {
      const lead = line.length - line.trimStart().length;
      const isCont = line.trim() !== '' && Math.abs(lead - open.msgCol) <= 1;
      const frag = isCont ? line.trim().split(/\s{2,}/)[0] : '';
      if (frag && !/^(Continued|Validated ID|HTTP\s)/.test(frag)) {
        open.entry.message = joinFragment(open.entry.message, frag);
      } else {
        open = null;
      }
    }
  }

  const entries = [...catalog.entries()].sort((a, b) => a[0] - b[0]);
  const body = entries
    .map(([code, e]) => {
      const eps = [...e.endpoints].slice(0, 6);
      return `  ${code}: { http: ${e.http}, message: ${JSON.stringify(e.message)}, endpoints: ${JSON.stringify(eps)} },`;
    })
    .join('\n');

  const out = `// GENERATED by scripts/gen-error-catalog.mjs. Do not edit by hand: npm run gen:errors.
// Source: VIDsigner API 3.0 REST manual, Annex III (VIDErrorCode catalog).

export interface VidErrorCatalogEntry {
  /** HTTP status the manual documents for the error. */
  http: number;
  /** Message from the manual (placeholders {0}, {1}... left unreplaced). */
  message: string;
  /** Endpoints where the manual documents it (at most 6). */
  endpoints: string[];
}

export const VID_ERROR_CATALOG: Readonly<Record<number, VidErrorCatalogEntry>> = {
${body}
};
`;
  const target = resolve(
    dirname(fileURLToPath(import.meta.url)),
    '../src/client/errors/catalog.generated.ts',
  );
  writeFileSync(target, out);
  // Format with the repository's prettier settings so the output is stable.
  const prettier = resolve(
    dirname(fileURLToPath(import.meta.url)),
    '../node_modules/prettier/bin/prettier.cjs',
  );
  spawnSync(process.execPath, [prettier, '--write', target], { stdio: 'inherit' });
  console.log(`Catalog: ${entries.length} codes -> ${target}`);
});
